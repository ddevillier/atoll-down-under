import {test,expect} from '@playwright/test';
import {clickButton} from '../../scripts/ui-actions.mjs';

for(const width of [1600,1024])test(`quiet creation controls retain editing, trials and saved fish at ${width}`,async({page})=>{
 await page.setViewportSize({width,height:Math.round(width*9/16)});
 const errors=[];page.on('pageerror',error=>errors.push(error.message));
 await page.goto('/');await page.waitForFunction(()=>window.atoll?.renderer.ready);
 await clickButton(page,{name:'Create a fish',exact:false});
 await expect(page.getByRole('heading',{name:'Create a fish',exact:true})).toBeVisible();
 for(const key of ['name','color','finColor','markingColor','marking','body','shapeMode','tail','dorsal','pectoral','mouth','size','speed','endurance','agility','diet','active','ability'])await expect(page.locator(`[data-config="${key}"]`)).toHaveCount(1);
 await page.locator('[data-config="shapeMode"]').selectOption('free');
 await expect(page.locator('#free-proportions')).toBeVisible();
 await page.getByRole('slider',{name:'Body length',exact:true}).fill('125');
 await page.getByRole('slider',{name:'Body depth',exact:true}).fill('80');
 await expect(page.locator('#proportion-note')).toHaveText('Shape stays fixed.');
 await page.locator('[data-config="shapeMode"]').selectOption('adapted');
 await expect(page.locator('#free-proportions')).toBeHidden();
 await expect(page.locator('#proportion-note')).toHaveText('Traits shape your fish.');
 for(const [key,value] of Object.entries({size:'180',speed:'220',endurance:'250',agility:'250'}))await page.locator(`[data-config="${key}"]`).fill(value);
 await page.locator('[data-config="ability"]').selectOption('spines');
 await expect(page.locator('#budget')).toHaveText('60 points over budget');
 await expect(page.getByRole('button',{name:'Keep fish',exact:true})).toBeDisabled();
 await expect(page.getByRole('button',{name:'Test swim',exact:true})).toBeDisabled();
 await expect(page.locator('#shape-note')).toContainText('Reduce body size');
 for(const [key,value] of Object.entries({size:'75',speed:'140',endurance:'150',agility:'150'}))await page.locator(`[data-config="${key}"]`).fill(value);
 await page.locator('[data-config="ability"]').selectOption('none');
 await page.locator('#fish-name').fill('Little Reef Friend');
 await expect(page.locator('#shape-note')).toHaveText('Fits reef shelters.');
 await expect(page.locator('.creation-status')).toContainText('Test swims are not saved.');
 await expect(page.getByText('Parts and colors change how your fish looks.',{exact:true})).toHaveCount(0);
 await expect(page.getByText('An invented animal. These choices describe how it lives in this game.',{exact:true})).toHaveCount(0);
 await page.screenshot({path:`artifacts/creation-quiet/editor-${width}.png`});
 expect(await page.locator('.panel').evaluate(element=>element.scrollWidth<=element.clientWidth+1)).toBe(true);
 await page.getByRole('button',{name:'Test swim',exact:true}).click();
 await expect(page.locator('.scene-name')).toContainText('Test swim');
 await expect(page.locator('.scene-name')).toContainText(/Unsaved|not saved|Nothing is saved/);
 expect(await page.evaluate(()=>window.atoll.simulation.trial)).toBe(true);
 await page.getByRole('button',{name:'Change my fish',exact:true}).click();
 await expect(page.locator('#fish-name')).toHaveValue('Little Reef Friend');
 await page.getByRole('button',{name:'Keep fish',exact:true}).click();
 await page.waitForFunction(()=>!!window.atoll.simulation?.creation&&!window.atoll.simulation.trial);
 const id=await page.evaluate(()=>window.atoll.simulation.creation.id);
 await page.locator('[data-action="guide"]').click();
 await expect(page.getByText('Invented fish',{exact:true})).toBeVisible();
 await expect(page.getByRole('button',{name:'Real species',exact:true})).toBeVisible();
 await expect(page.getByText('No memories yet.',{exact:true})).toBeVisible();
 await page.screenshot({path:`artifacts/creation-quiet/guide-${width}.png`});
 expect(await page.locator('.panel').evaluate(element=>element.scrollWidth<=element.clientWidth+1)).toBe(true);
 await page.getByRole('button',{name:'Return',exact:true}).click();
 const creations=page.getByRole('button',{name:'My creations',exact:true});
 if(!await creations.isVisible()){
  const activity=page.getByRole('button',{name:'Activity',exact:true});
  if(await activity.isVisible())await activity.click();
  await page.getByText('Activity details',{exact:true}).click();
 }
 await creations.click();
 const row=page.locator('.creation-row').filter({has:page.getByRole('heading',{name:'Little Reef Friend',exact:true})});
 for(const label of ['Resume','New swim','Make a variation','Rename'])await expect(row.getByRole('button',{name:label,exact:true})).toBeVisible();
 await page.screenshot({path:`artifacts/creation-quiet/shelf-${width}.png`});
 await row.getByRole('button',{name:'Resume',exact:true}).click();
 expect(await page.evaluate(()=>window.atoll.simulation.creation.id)).toBe(id);
 expect(errors).toEqual([]);
});
