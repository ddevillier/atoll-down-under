export function pathWeight(u,v,points,radius){
 let nearest=Infinity,progress=0,total=0;const lengths=[];
 for(let i=1;i<points.length;i++){const d=Math.hypot(points[i][0]-points[i-1][0],points[i][1]-points[i-1][1]);lengths.push(d);total+=d;}
 let along=0;
 for(let i=1;i<points.length;i++){
  const [ax,ay]=points[i-1],[bx,by]=points[i],dx=bx-ax,dy=by-ay,l=lengths[i-1];
  const t=l?Math.max(0,Math.min(1,((u-ax)*dx+(v-ay)*dy)/(l*l))):0,d=Math.hypot(u-ax-dx*t,v-ay-dy*t);
  if(d<nearest){nearest=d;progress=(along+l*t)/(total||1);}along+=l;
 }
 const edge=Math.max(0,1-nearest/radius);return {weight:edge*edge*(3-2*edge)*progress**1.5,progress};
}
